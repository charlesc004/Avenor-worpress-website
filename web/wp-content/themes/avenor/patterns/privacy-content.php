<h1 class="wp-block-heading">Privacy, in plain language.</h1>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>This notice explains how AVENOR handles information submitted through this website. Please do not include sensitive or confidential information in an initial inquiry.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Information we collect</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When you submit the inquiry form, we store your name, email address, optional company and service, message, acknowledgment time, workflow status, and notification delivery state. These details are used to review and respond to your inquiry.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Access and security</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Inquiry records are private and accessible only to authorized administrators. They are excluded from public search, public content APIs, and sitemaps. Your network address is hashed with a site secret for temporary abuse controls rather than saved with your inquiry.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Retention and deletion</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The default retention period is 365 days. Administrators may configure a different period or delete records earlier. Scheduled cleanup removes expired records in daily batches. Backup copies follow a separate retention policy.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Email notifications</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>An inquiry is saved before notification is attempted. Notification messages contain an administration link rather than your full message. If email delivery fails, your inquiry remains available to authorized administrators.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Your choices</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>You can request access, correction, or deletion using the contact form. WordPress personal-data export and erasure tools include inquiries associated with your email address. Necessary administrative cookies support authenticated access; the public site does not include third-party advertising trackers.</p>
<!-- /wp:paragraph -->
